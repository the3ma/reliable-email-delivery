import { NagSuppressions } from 'cdk-nag';
import type { EmailDeliveryStack } from './email-delivery-stack';

const KMS_GRANT_ACTIONS = {
  id: 'AwsSolutions-IAM5',
  reason:
    'kms:GenerateDataKey* / kms:ReEncrypt* are the action sets of the CDK SQS/DynamoDB key grants; the resource is the single stack key ARN, not *.',
  appliesTo: ['Action::kms:GenerateDataKey*', 'Action::kms:ReEncrypt*'],
};

/** cdk-nag suppressions; each one names the rule, the exact finding (appliesTo), and why. */
export function applyNagSuppressions(stack: EmailDeliveryStack): void {
  const { functions, toggles } = stack;
  const all = [
    functions.notifierImmediate,
    functions.notifierDigest,
    functions.processor,
    functions.feedback,
  ];

  NagSuppressions.addResourceSuppressions(all, [
    {
      id: 'AwsSolutions-L1',
      reason:
        'The runtime is pinned to Node.js 22 by the integration contract (packages/functions targets node22).',
    },
  ]);

  NagSuppressions.addResourceSuppressions(
    functions.roles,
    [
      KMS_GRANT_ACTIONS,
      {
        id: 'AwsSolutions-IAM5',
        reason:
          'Resource * only for actions without resource-level permissions: xray:PutTraceSegments / PutTelemetryRecords (active tracing) and, for the processor, ses:GetSuppressedDestination.',
        appliesTo: ['Resource::*'],
      },
    ],
    true,
  );

  NagSuppressions.addResourceSuppressions(
    functions.processor.role ?? functions.processor,
    [
      {
        id: 'AwsSolutions-IAM5',
        reason:
          'GetParametersByPath on the toggle path: the path ARN plus the parameters directly below it (send-emails, record-deliveries), nothing else.',
        appliesTo: [
          { regex: `/^Resource::arn:.*:ssm:.*:parameter/${toggles.path.slice(1)}\\*$/g` },
        ],
      },
    ],
    true,
  );

  NagSuppressions.addResourceSuppressions(
    functions.schedulerRole,
    [
      KMS_GRANT_ACTIONS,
      {
        id: 'AwsSolutions-IAM5',
        reason:
          'Grant generated by the Scheduler Lambda target: InvokeFunction on the digest function ARN and its versions/aliases (<arn>:*), one function only.',
        appliesTo: [{ regex: '/^Resource::<FunctionsNotifierDigest[0-9A-F]{8}\\.Arn>:\\*$/g' }],
      },
    ],
    true,
  );

  if (stack.redrive.operatorRole) {
    NagSuppressions.addResourceSuppressions(stack.redrive.operatorRole, [KMS_GRANT_ACTIONS], true);
  }
}
